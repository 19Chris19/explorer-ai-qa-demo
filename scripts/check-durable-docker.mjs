import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';

const base = process.env.SYNTHETIC_WEBSITE_URL;
if (!/^http:\/\/127\.0\.0\.1:\d+$/u.test(base || '')) throw new Error('Synthetic loopback website URL required');
const health = await (await fetch(`${base}/api/qa/health`)).json();
assert.equal(health.durableTasksSupported, true);
const create = await fetch(`${base}/api/qa/conversations`, { method: 'POST' });
const cookie = create.headers.get('set-cookie').split(';')[0];
const headers = { Cookie: cookie, Origin: base, 'Content-Type': 'application/json' };
const conversationId = (await create.json()).conversation.conversationId;
const input = { question: 'synthetic slow Docker check', conversationId, requestId: randomUUID() };
const submit = body => fetch(`${base}/api/qa/tasks`, { method: 'POST', headers, body: JSON.stringify(body) });
const accepted = await submit(input); assert.equal(accepted.status, 202);
const { task } = await accepted.json();
const repeat = await (await submit(input)).json(); assert.equal(repeat.task.id, task.id);
assert.equal((await submit({ ...input, question: 'conflict' })).status, 409);
assert.equal((await fetch(`${base}/api/qa/tasks/${task.id}`)).status, 404);
const signal = new AbortController();
const first = await fetch(`${base}/api/qa/tasks/${task.id}/events`, { headers, signal: signal.signal });
await first.body.getReader().read(); signal.abort();
const continued = await (await fetch(`${base}/api/qa/tasks/${task.id}/events`, { headers })).text();
assert.equal([...continued.matchAll(/event: done\n/gu)].length, 1);
const result = await (await fetch(`${base}/api/qa/tasks/${task.id}`, { headers })).json();
assert.equal(result.task.status, 'succeeded');
const answer = result.snapshot.events.filter(event => event.event === 'delta').map(event => event.data.text).join('');
assert.equal(answer, '## 合成回答\n\n| 项目 | 数值 |\n| --- | --- |\n| Docker |  123  |\n');
assert.equal(result.snapshot.events.filter(event => event.event === 'sources').length, 1);
const history = await (await fetch(`${base}/api/qa/conversations/${conversationId}`, { headers })).json();
assert.equal(history.messages.filter(message => message.role === 'assistant').length, 1);
assert.equal(history.messages.find(message => message.role === 'assistant').content, answer);
for (const path of ['/admin', '/internal/provider-a/tasks', '/api/qa/tasks/fake/debug']) assert.equal((await fetch(base + path)).status, 404);
assert.equal((await fetch(`${base}/task-stream.mjs`)).status, 200);
const stopped = (await (await submit({ ...input, question: 'synthetic slow cancellation', requestId: randomUUID() })).json()).task;
assert.equal((await fetch(`${base}/api/qa/tasks/${stopped.id}`, { method: 'DELETE', headers })).status, 200);
assert.equal((await (await fetch(`${base}/api/qa/tasks/${stopped.id}`, { headers })).json()).task.status, 'cancelled');
console.log(JSON.stringify({ result: 'PASS', synthetic: true, realIMA: false, taskReplay: true, uniqueHistory: true, exactWhitespace: true, explicitCancel: true, managementBlocked: true }));
